CREATE TABLE russian_locations (
  id text PRIMARY KEY,
  kind text NOT NULL CHECK (kind IN ('region', 'locality')),
  parent_id text REFERENCES russian_locations(id) ON DELETE RESTRICT,
  name text NOT NULL,
  slug text NOT NULL,
  active boolean NOT NULL DEFAULT true,
  latitude numeric(9, 6),
  longitude numeric(9, 6),
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT russian_locations_id_slug CHECK (id ~ '^[a-z0-9]+(?:-[a-z0-9]+)*$'),
  CONSTRAINT russian_locations_slug_format CHECK (slug ~ '^[a-z0-9]+(?:[-_][a-z0-9]+)*$'),
  CONSTRAINT russian_locations_name_nonblank CHECK (length(btrim(name)) > 0),
  CONSTRAINT russian_locations_hierarchy CHECK (
    (kind = 'region' AND parent_id IS NULL)
    OR (kind = 'locality' AND parent_id IS NOT NULL)
  ),
  CONSTRAINT russian_locations_coordinates CHECK (
    (latitude IS NULL AND longitude IS NULL)
    OR (
      latitude BETWEEN -90 AND 90
      AND longitude BETWEEN -180 AND 180
    )
  )
);

CREATE INDEX russian_locations_regions
  ON russian_locations (name, id)
  WHERE kind = 'region' AND active = true;

CREATE INDEX russian_locations_localities
  ON russian_locations (parent_id, name, id)
  WHERE kind = 'locality' AND active = true;

