CREATE TABLE contractor_service_areas (
  account_id uuid NOT NULL REFERENCES contractor_profiles(account_id) ON DELETE CASCADE,
  location_id text NOT NULL REFERENCES russian_locations(id) ON DELETE RESTRICT,
  PRIMARY KEY (account_id, location_id)
);

CREATE INDEX contractor_service_areas_location
  ON contractor_service_areas (location_id, account_id);

DO $$
BEGIN
  IF EXISTS (
    SELECT 1
    FROM contractor_profiles cp
    CROSS JOIN LATERAL jsonb_array_elements_text(cp.service_location_ids) AS legacy(location_id)
    LEFT JOIN russian_locations rl ON rl.id = legacy.location_id
    WHERE rl.id IS NULL
  ) THEN
    RAISE EXCEPTION 'Existing contractor profiles contain unknown Russian location IDs';
  END IF;
END $$;

